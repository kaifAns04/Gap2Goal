/**
 * Returns all catalogue entries that mention the given skill name.
 * Case-insensitive, partial-match friendly.
 */
export function getResourcesForSkill(skillName) {
  const normalized = skillName.toLowerCase().replace(/[.\s]/g, '');
  return RESOURCE_CATALOGUE.filter(r => {
    const rSkill = r.skill.toLowerCase().replace(/[.\s]/g, '');
    return rSkill.includes(normalized) || normalized.includes(rSkill);
  });
}

/**
 * Returns the full catalogue as a compact JSON string for inclusion in Gemini prompts.
 * Only sends fields needed for selection — not the `why` field (Gemini writes its own).
 */
export function getCatalogueForPrompt() {
  return RESOURCE_CATALOGUE.map(({ id, skill, title, platform, type, level, duration, url }) => ({
    id, skill, title, platform, type, level, duration: duration || 'self-paced', url,
  }));
}
